#!/usr/bin/env bash
# =============================================================
#  Этап 2. Обработка ошибок параметров командной строки.
#  В каждом сценарии эмулятор должен показать сообщение об
#  ошибке в консоли и завершиться с кодом 1.
# =============================================================
cd "$(dirname "$0")/.."

echo "=== 1. --vfs: несуществующий путь ==="
python3 -m src.main --vfs no_such_dir
echo "Код возврата: $?"
echo

echo "=== 2. --vfs: указан файл вместо директории ==="
python3 -m src.main --vfs README.md
echo "Код возврата: $?"
echo

echo "=== 3. --script: несуществующий файл ==="
python3 -m src.main --script no_such_script.txt
echo "Код возврата: $?"
echo

echo "=== 4. --script: указана директория вместо файла ==="
python3 -m src.main --script demo
echo "Код возврата: $?"
echo

echo "Все сценарии ошибок выполнены (все коды должны быть 1)."
